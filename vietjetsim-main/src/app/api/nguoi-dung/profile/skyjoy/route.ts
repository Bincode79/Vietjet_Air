import { NextRequest, NextResponse } from 'next/server';
import { verifyAuthRequest } from '@/lib/auth';
import { validateCsrfOrReject } from '@/lib/csrf';
import { rateLimit } from '@/lib/rate-limit';
import { sql } from '@/lib/neon';
import { writeAuditLog } from '@/lib/db';
import { sendOtpSms } from '@/lib/sms';

export async function PATCH(request: NextRequest) {
  try {
    const csrfError = await validateCsrfOrReject(request);
    if (csrfError) return csrfError;

    const limited = rateLimit(request, { windowMs: 60_000, maxRequests: 5 });
    if (limited) return limited;

    const { user: auth, error, response } = await verifyAuthRequest(request);
    if (error || !auth) return response!;

    const body = await request.json();
    const action = body?.action; // 'link' | 'unlink' | 'verify'
    const skyjoyId = typeof body?.skyjoy_member_id === 'string' ? body.skyjoy_member_id.trim().toUpperCase() : '';
    const otp = typeof body?.otp === 'string' ? body.otp.trim() : '';

    // Validate SkyJoy ID format: SJ + 8-10 digits
    const skyjoyPattern = /^SJ\d{8,10}$/;

    if (action === 'link') {
      if (!skyjoyPattern.test(skyjoyId)) {
        return NextResponse.json(
          { error: 'Mã thành viên SkyJoy không hợp lệ. Định dạng: SJ + 8-10 chữ số (VD: SJ12345678).' },
          { status: 400 }
        );
      }

      // Check if already linked to another account
      const existing = await sql`
        SELECT id FROM user_profiles WHERE skyjoy_member_id = ${skyjoyId} AND id <> ${auth.userId}
      `;
      if ((existing as unknown[]).length > 0) {
        return NextResponse.json(
          { error: 'Mã SkyJoy này đã được liên kết với tài khoản khác.' },
          { status: 409 }
        );
      }

      // Check if user already has a different SkyJoy ID
      const current = await sql`
        SELECT skyjoy_member_id FROM user_profiles WHERE id = ${auth.userId}
      `;
      const currentId = (current as { skyjoy_member_id: string | null }[])[0]?.skyjoy_member_id;
      if (currentId && currentId !== skyjoyId) {
        return NextResponse.json(
          { error: 'Tài khoản đã liên kết với mã SkyJoy khác. Vui lòng hủy liên kết trước.' },
          { status: 409 }
        );
      }

      // Send OTP to phone for verification
      const userPhone = await sql`
        SELECT phone FROM user_profiles WHERE id = ${auth.userId}
      `;
      const phone = (userPhone as { phone: string | null }[])[0]?.phone;
      if (!phone) {
        return NextResponse.json(
          { error: 'Tài khoản chưa có số điện thoại. Vui lòng cập nhật SĐT trước.' },
          { status: 400 }
        );
      }

      // Store pending skyjoy_id in a temp table or use account_recovery with purpose
      await sql`
        INSERT INTO account_recovery (user_id, email, token, token_expires_at, used)
        VALUES (${auth.userId}, ${skyjoyId}, ${crypto.randomUUID()}, NOW() + INTERVAL '10 minutes', true)
        ON CONFLICT (user_id) DO UPDATE SET
          email = EXCLUDED.email,
          token = EXCLUDED.token,
          token_expires_at = EXCLUDED.token_expires_at,
          used = EXCLUDED.used
      `;

      // Send OTP via SMS
      await sendOtpSms({
        phone,
        code: '', // Will be generated by sendOtpSms
        purpose: 'skyjoy_link',
      }).catch((err) => console.error('[SKYJOY-LINK] SMS error:', err));

      return NextResponse.json({
        success: true,
        message: 'Đã gửi mã OTP đến số điện thoại của bạn. Vui lòng nhập mã để xác thực.',
        requiresOtp: true,
      });
    }

    if (action === 'verify') {
      if (!otp || otp.length !== 6) {
        return NextResponse.json(
          { error: 'Mã OTP không hợp lệ (6 chữ số).' },
          { status: 400 }
        );
      }

      // Verify OTP from account_recovery (simplified - in production use phone_otp table)
      const recovery = await sql`
        SELECT email as skyjoy_id FROM account_recovery
        WHERE user_id = ${auth.userId} AND used = true AND token_expires_at > NOW()
        ORDER BY created_at DESC LIMIT 1
      `;
      const pendingSkyjoyId = (recovery as { skyjoy_id: string }[])[0]?.skyjoy_id;

      if (!pendingSkyjoyId) {
        return NextResponse.json(
          { error: 'Không tìm thấy yêu cầu liên kết đang chờ. Vui lòng thử lại.' },
          { status: 400 }
        );
      }

      // In production: verify OTP with phone_otp table
      // For now, accept any 6-digit OTP for demo
      if (otp !== '123456') { // Demo OTP
        return NextResponse.json(
          { error: 'Mã OTP không đúng. Vui lòng thử lại.' },
          { status: 401 }
        );
      }

      // Link SkyJoy ID
      await sql`
        UPDATE user_profiles
        SET skyjoy_member_id = ${pendingSkyjoyId}, updated_at = NOW()
        WHERE id = ${auth.userId}
      `;

      // Clean up recovery record
      await sql`
        DELETE FROM account_recovery WHERE user_id = ${auth.userId} AND email = ${pendingSkyjoyId}
      `;

      // Audit log
      await writeAuditLog({
        adminId: auth.userId,
        adminEmail: auth.email,
        action: 'link_skyjoy',
        targetType: 'user',
        targetId: auth.userId,
        detailsJson: JSON.stringify({ skyjoy_member_id: pendingSkyjoyId }),
        status: 'success',
      }).catch((err) => console.error('[SKYJOY-LINK-AUDIT] error:', err));

      return NextResponse.json({
        success: true,
        message: 'Liên kết SkyJoy thành công!',
        skyjoyMemberId: pendingSkyjoyId,
      });
    }

    if (action === 'unlink') {
      await sql`
        UPDATE user_profiles
        SET skyjoy_member_id = NULL, updated_at = NOW()
        WHERE id = ${auth.userId}
      `;

      await writeAuditLog({
        adminId: auth.userId,
        adminEmail: auth.email,
        action: 'unlink_skyjoy',
        targetType: 'user',
        targetId: auth.userId,
        detailsJson: JSON.stringify({}),
        status: 'success',
      }).catch((err) => console.error('[SKYJOY-UNLINK-AUDIT] error:', err));

      return NextResponse.json({
        success: true,
        message: 'Đã hủy liên kết SkyJoy.',
      });
    }

    return NextResponse.json(
      { error: 'Hành động không hợp lệ. Chỉ hỗ trợ: link, verify, unlink.' },
      { status: 400 }
    );
  } catch (error) {
    console.error('Error linking SkyJoy:', error);
    return NextResponse.json(
      { error: 'Đã xảy ra lỗi. Vui lòng thử lại.' },
      { status: 500 }
    );
  }
}

export async function GET(request: NextRequest) {
  try {
    const { user: auth, error, response } = await verifyAuthRequest(request);
    if (error || !auth) return response!;

    const current = await sql`
      SELECT skyjoy_member_id FROM user_profiles WHERE id = ${auth.userId}
    `;
    const skyjoyId = (current as { skyjoy_member_id: string | null }[])[0]?.skyjoy_member_id;

    return NextResponse.json({
      skyjoyMemberId: skyjoyId,
      isLinked: !!skyjoyId,
    });
  } catch (error) {
    console.error('Error fetching SkyJoy status:', error);
    return NextResponse.json(
      { error: 'Không thể tải trạng thái SkyJoy.' },
      { status: 500 }
    );
  }
}